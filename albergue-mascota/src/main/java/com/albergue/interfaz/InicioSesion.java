    private void cargarLogo() {

        java.net.URL ruta = getClass().getResource(
                "/imagenes/logo.jpg"
        );

        if (ruta != null) {

            javax.swing.ImageIcon imagen
                    = new javax.swing.ImageIcon(ruta);

            java.awt.Image imagenAjustada
                    = imagen.getImage().getScaledInstance(
                            65, 65,
                            java.awt.Image.SCALE_SMOOTH
                    );

            lblLogo.setIcon(
                    new javax.swing.ImageIcon(imagenAjustada)
            );

        } else {
            System.out.println("No se encontró el logo.");
        }
    }

    /**
     * Configuración de eventos y lógica para los botones y controles.
     */
    private void configurarEventos() {
        // Limpiar texto por defecto
        txtContrasena.setText("");

        // 1. Checkbox Mostrar / Ocultar Contraseña
        chkMostrarContrasena.addActionListener(e -> {
            if (chkMostrarContrasena.isSelected()) {
                txtContrasena.setEchoChar((char) 0); // Muestra la contraseña en texto plano
            } else {
                txtContrasena.setEchoChar('•'); // Oculta la contraseña con puntos cifrados
            }
        });

        // 2. Botón Ingresar
        btnIngresar.addActionListener(e -> validarAcceso());

        // 3. Botón Limpiar
        btnLimpiar.addActionListener(e -> limpiarCampos());

        // 4. Botón Salir con confirmación
        btnSalir.addActionListener(e -> {
            int confirm = JOptionPane.showConfirmDialog(this,
                    "¿Estás seguro de que deseas salir?",
                    "Confirmar salida",
                    JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                dispose();
            }
        });

        // Opcional: Presionar "Enter" para iniciar sesión rápido
        java.awt.event.ActionListener enterAction = e -> validarAcceso();
        txtUsuario.addActionListener(enterAction);
        txtContrasena.addActionListener(enterAction);
    }

    /**
     * Valida las credenciales ingresadas usando la interfaz Autenticable y la
     * clase Usuario.
     */
    private void validarAcceso() {
        
        String usuarioIngresado = txtUsuario.getText().trim();
        String contrasenaIngresada = new String(txtContrasena.getPassword());

        // Validar campos vacíos
        if (usuarioIngresado.isEmpty() || contrasenaIngresada.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Por favor, complete todos los campos.",
                    "Campos vacíos",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Credenciales del administrador
        Autenticable admin = new Usuario("admin", "1234", "Administrador");

        if (admin.autenticar(usuarioIngresado, contrasenaIngresada)) {

            JOptionPane.showMessageDialog(this,
                    "¡Bienvenido al sistema, "
                    + ((Usuario) admin).getNombre() + "!",
                    "Acceso Concedido",
                    JOptionPane.INFORMATION_MESSAGE);

            VentanaPrincipalAlbergue ventana
                    = new VentanaPrincipalAlbergue();

            ventana.setLocationRelativeTo(null);
            ventana.setVisible(true);

            this.dispose();

        } else {
            intentosRestantes--;

            txtContrasena.setText("");
            txtContrasena.requestFocus();

            if (intentosRestantes > 0) {
                JOptionPane.showMessageDialog(this,
                        "Usuario o contraseña incorrectos.\n"
                        + "Te quedan " + intentosRestantes + " intentos.",
                        "Error de autenticación",
                        JOptionPane.WARNING_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Has agotado los 3 intentos permitidos.\n"
                        + "El sistema cerrará el inicio de sesión.",
                        "Acceso bloqueado",
                        JOptionPane.ERROR_MESSAGE);

                dispose();
            }
        }
    }

    /**
     * Limpia los campos del formulario.
     */
    private void limpiarCampos() {
        txtUsuario.setText("");
        txtContrasena.setText("");
        chkMostrarContrasena.setSelected(false);
        txtContrasena.setEchoChar('•'); // Asegurar cifrado activo
        txtUsuario.requestFocus();
    }

