    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String usuario = txtUsuario.getText().trim();
        String contrasena = new String(pwdContrasena.getPassword());

        // 1. Campos vacíos
        if (usuario.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese usuario y contraseña.",
                    "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            (usuario.isEmpty() ? txtUsuario : pwdContrasena).requestFocus();
            return;
        }

        // 2. Validación con la lógica del sistema (interfaz Autenticable)
        if (SistemaAlbergueMascota.autenticar(usuario, contrasena)) {
            JOptionPane.showMessageDialog(this, "¡Bienvenido, " + usuario + "!",
                    "Acceso concedido", JOptionPane.INFORMATION_MESSAGE);
            dispose();                          // cierra el login
            if (alIngresar != null) {
                alIngresar.run();               // abre la ventana principal
            }
            return;
        }

        // 3. Credenciales incorrectas
        intentosFallidos++;
        int restantes = MAX_INTENTOS - intentosFallidos;
        if (restantes > 0) {
            JOptionPane.showMessageDialog(this,
                    "Usuario o contraseña incorrectos.\nIntentos restantes: " + restantes,
                    "Error de acceso", JOptionPane.ERROR_MESSAGE);
            pwdContrasena.setText("");
            pwdContrasena.requestFocus();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Superó el número máximo de intentos (" + MAX_INTENTOS + ").\nEl sistema se cerrará.",
                    "Acceso bloqueado", JOptionPane.ERROR_MESSAGE);
            System.exit(0);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

    private void btnLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimpiarActionPerformed
        txtUsuario.setText("");
        pwdContrasena.setText("");
        chkMostrar.setSelected(false);
        pwdContrasena.setEchoChar(caracterOculto);
        txtUsuario.requestFocus();
    }//GEN-LAST:event_btnLimpiarActionPerformed

    private void btnSalirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalirActionPerformed
        Object[] opciones = {"Sí", "No"};
        int opcion = JOptionPane.showOptionDialog(this,
                "¿Desea salir del sistema?", "Salir",
                JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[1]);
        if (opcion == 0) {
            System.exit(0);
        }
    }//GEN-LAST:event_btnSalirActionPerformed

    private void chkMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_chkMostrarActionPerformed
        // (char) 0 muestra el texto; caracterOculto lo vuelve a ocultar
        pwdContrasena.setEchoChar(chkMostrar.isSelected() ? (char) 0 : caracterOculto);
    }//GEN-LAST:event_chkMostrarActionPerformed

